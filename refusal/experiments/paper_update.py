ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'figures/co_learning'
INPUTS={}


def source(relative):
    p=ROOT/relative
    INPUTS[relative]=hashlib.sha256(p.read_bytes()).hexdigest()
    return p


def table(name,columns,head,rows):
    text=['% Generated by experiments/paper_update.py from audited summaries.',r'\begin{tabular}{'+columns+'}',r'\toprule',head+r' \\',r'\midrule']
    text.extend(' & '.join(str(v) for v in row)+r' \\' for row in rows)
    text.extend([r'\bottomrule',r'\end{tabular}'])
    (OUT/name).write_text('\n'.join(text)+'\n')


